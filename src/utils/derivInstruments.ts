/**
 * Quick helper to get instrument by symbol (case-insensitive)
 */
export function getDerivInstrument(symbol: string): DerivInstrument | undefined {
  const clean = symbol.replace('/', '').toUpperCase();
  return DERIV_INSTRUMENTS.find(
    (i) => i.symbol.toUpperCase() === clean || i.symbol.replace('_', '').toUpperCase() === clean.replace('_', '')
  );
}

/**
 * Filter instruments by category
 */
export function getInstrumentsByCategory(
  category: 'ALL' | 'VOLATILITY' | 'CRASH_BOOM' | 'STEP_JUMP' | 'CRYPTO' | 'INDICES' | 'COMMODITIES' | 'FOREX'
): DerivInstrument[] {
  if (category === 'ALL') return DERIV_INSTRUMENTS;
  return DERIV_INSTRUMENTS.filter((i) => i.category === category);
}

